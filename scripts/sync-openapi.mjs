#!/usr/bin/env node
/**
 * Refresh openapi/orbitwrite.json: the part of Orbitwrite's API this plugin
 * calls, cut from the full spec.
 *
 *   npm run openapi:sync                       (from https://orbitwrite.com)
 *   npm run openapi:sync -- <url or file>      (staging, or a local copy)
 *
 * The plugin talks to Orbitwrite through a small hand-written PHP client
 * (includes/class-api.php) rather than generated code, so this file is how it
 * stays honest: the tests validate every request the plugin builds, and every
 * response the mock Orbitwrite gives, against it. When Orbitwrite changes a
 * route the plugin uses, re-running this and the tests says so.
 *
 * Only the operations below are kept, with the component schemas they
 * reference. No dependencies; Node 18+.
 */
import { readFile, writeFile } from 'node:fs/promises';

const DEFAULT_SOURCE = 'https://orbitwrite.com/api/v1/openapi.json';
const OUT = new URL( '../openapi/orbitwrite.json', import.meta.url );

/** Every operation the plugin calls. Add to this when it calls a new one. */
export const OPERATIONS = [
	[ 'get', '/api/v1/me' ],
	[ 'get', '/api/v1/connected-accounts' ],
	[ 'get', '/api/v1/platforms' ],
	[ 'get', '/api/v1/scheduling/suggestions' ],
	[ 'post', '/api/v1/media/create-upload-url' ],
	[ 'post', '/api/v1/posts' ],
	[ 'get', '/api/v1/posts' ],
	[ 'post', '/api/v1/posts/discard' ],
	[ 'get', '/api/v1/analytics/overview' ],
	[ 'get', '/api/v1/analytics/posts' ],
];

async function load( source ) {
	if ( /^https?:\/\//.test( source ) ) {
		const response = await fetch( source, {
			headers: { Accept: 'application/json' },
		} );
		if ( ! response.ok ) {
			throw new Error( `${ source } answered ${ response.status }` );
		}
		return response.json();
	}
	return JSON.parse( await readFile( source, 'utf8' ) );
}

/** Every `#/components/schemas/X` reachable from a value. */
function collectRefs( value, spec, found = new Set() ) {
	if ( Array.isArray( value ) ) {
		value.forEach( ( item ) => collectRefs( item, spec, found ) );
	} else if ( value && typeof value === 'object' ) {
		for ( const [ key, item ] of Object.entries( value ) ) {
			if ( key === '$ref' && typeof item === 'string' ) {
				const name = item.replace( '#/components/schemas/', '' );
				if ( ! found.has( name ) ) {
					found.add( name );
					collectRefs( spec.components.schemas[ name ], spec, found );
				}
			} else {
				collectRefs( item, spec, found );
			}
		}
	}
	return found;
}

const source = process.argv[ 2 ] || DEFAULT_SOURCE;
const spec = await load( source );

const paths = {};
for ( const [ method, path ] of OPERATIONS ) {
	const operation = spec.paths?.[ path ]?.[ method ];
	if ( ! operation ) {
		throw new Error(
			`${ method.toUpperCase() } ${ path } is missing from ${ source }. The plugin calls it; check what changed.`
		);
	}
	paths[ path ] = { ...paths[ path ], [ method ]: operation };
}

const schemas = {};
for ( const name of [ ...collectRefs( paths, spec ) ].sort() ) {
	schemas[ name ] = spec.components.schemas[ name ];
}

const subset = {
	openapi: spec.openapi,
	info: {
		...spec.info,
		description:
			'The part of the Orbitwrite API this plugin calls. Generated by scripts/sync-openapi.mjs; do not edit by hand.',
	},
	paths,
	components: { schemas },
};

await writeFile( OUT, JSON.stringify( subset, null, '\t' ) + '\n' );
// eslint-disable-next-line no-console
console.log(
	`Wrote ${ OPERATIONS.length } operations and ${
		Object.keys( schemas ).length
	} schemas to openapi/orbitwrite.json`
);
